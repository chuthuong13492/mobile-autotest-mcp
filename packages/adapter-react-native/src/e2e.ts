/**
 * Maestro and Detox on the run's device (RN-003; Maestro 2.11.0 and Detox 20.51.4 verified).
 *
 * - Maestro: `maestro test --udid <UDID|emulator-port> --format JUNIT --output <runDir>/…/maestro.xml
 *   --test-output-dir <runDir>/…/maestro --no-ansi <flows>`. The app under test must already be installed on the
 *   device (`manage_simulator {action: "install"}`); AutoTest does not build apps.
 * - Detox: `node node_modules/detox/local-cli/cli.js test --config-path <runDir>/…/detox.config.js
 *   --configuration <name> … <e2e files>`. Detox's own `--device-name` selects simulators by type only, which could
 *   pick a device AutoTest does not own, so the run writes a config (ExecutionSpec `files`) that extends the
 *   project's config and pins the configuration to the run's device: `{id: <UDID>}` on iOS, `{adbName: <serial>}`
 *   on Android. The app must be built beforehand (`detox build` runs a shell command from the project and is not
 *   allowed); Detox installs it. On iOS, Detox's framework cache lives in HOME, which is per run, so it is built first.
 */
import {
  buildSpec,
  flag,
  flagRunPath,
  parseJUnitXml,
  runnerOutput,
  workspacePath,
  type ExecutionSpec,
  type NormalizedResult,
  type TestTarget,
} from '@autotest/adapter-sdk';

export const DETOX_SCRIPT = 'node_modules/detox/local-cli/cli.js';
export const maestroReport = (attemptNo: number) => runnerOutput(attemptNo, 'maestro.xml');
export const detoxReport = (attemptNo: number) => runnerOutput(attemptNo, 'detox.json');
const detoxConfig = (attemptNo: number) => runnerOutput(attemptNo, 'detox.config.js');

type Device = { readonly platform: 'ios' | 'android'; readonly id: string };

const common = (device: Device, timeoutMs: number) => ({
  cwd: '.',
  envNeeds: [],
  timeoutMs,
  cancellation: 'graceful_then_group' as const,
  requires:
    device.platform === 'ios'
      ? { host: 'macos' as const, device: 'simulator' as const }
      : { host: 'any' as const, device: 'emulator' as const },
});

export function maestroSpec(
  attemptNo: number,
  flows: readonly string[],
  device: Device,
  timeoutMs: number,
): ExecutionSpec {
  return buildSpec({
    ...common(device, timeoutMs),
    executable: 'maestro',
    args: [
      { kind: 'word', value: 'test' },
      flag('--udid', device.id),
      flag('--format', 'JUNIT'),
      flagRunPath('--output', maestroReport(attemptNo)),
      flagRunPath('--test-output-dir', `attempts/${attemptNo}/maestro`),
      flag('--no-ansi'),
      ...[...new Set(flows)].sort().map((f) => workspacePath(f)),
    ],
    expectedOutputs: [{ kind: 'junit', rel: maestroReport(attemptNo) }],
  });
}

/** The generated Detox config: the project's config with one configuration pinned to the run's device. */
export function detoxPinConfig(projectConfig: string, configuration: string, device: Device): string {
  const pinned =
    device.platform === 'ios'
      ? { type: 'ios.simulator', device: { id: device.id } }
      : { type: 'android.attached', device: { adbName: device.id } };
  return [
    '// Generated by AutoTest (RN-003): the project Detox config, with one configuration pinned to the run device.',
    "const path = require('node:path');",
    'module.exports = {',
    `  extends: path.join(process.cwd(), ${JSON.stringify(projectConfig)}),`,
    `  configurations: { ${JSON.stringify(configuration)}: { device: ${JSON.stringify(pinned)} } },`,
    '};',
    '',
  ].join('\n');
}

export function detoxSpecs(
  attemptNo: number,
  args: { projectConfig: string; configuration: string; files: readonly string[]; device: Device; timeoutMs: number },
): ExecutionSpec[] {
  const base = common(args.device, args.timeoutMs);
  const framework =
    args.device.platform === 'ios'
      ? [
          buildSpec({
            ...base,
            executable: 'node',
            args: [workspacePath(DETOX_SCRIPT), { kind: 'word', value: 'build-framework-cache' }],
            expectedOutputs: [],
          }),
        ]
      : [];
  return [
    ...framework,
    buildSpec({
      ...base,
      executable: 'node',
      args: [
        workspacePath(DETOX_SCRIPT),
        { kind: 'word', value: 'test' },
        flagRunPath('--config-path', detoxConfig(attemptNo)),
        flag('--configuration', args.configuration),
        flagRunPath('--artifacts-location', `attempts/${attemptNo}/detox-artifacts`),
        flag('--record-logs', 'failing'),
        flag('--take-screenshots', 'failing'),
        flag('--json'),
        flagRunPath('--outputFile', detoxReport(attemptNo)),
        ...[...new Set(args.files)].sort().map((f) => workspacePath(f)),
      ],
      files: [
        { rel: detoxConfig(attemptNo), content: detoxPinConfig(args.projectConfig, args.configuration, args.device) },
      ],
      expectedOutputs: [{ kind: 'runner_json', rel: detoxReport(attemptNo) }],
    }),
  ];
}

/** Maps Maestro's JUnit report to flow targets: a test case is named after its flow (file name or `name:`). */
export function parseMaestroReport(xml: string | undefined, targets: readonly TestTarget[]): NormalizedResult[] {
  if (!xml) return [];
  const byName = new Map(targets.map((t) => [t.path.slice(t.path.lastIndexOf('/') + 1).replace(/\.ya?ml$/, ''), t]));
  return parseJUnitXml(xml).flatMap((c) => {
    const t = byName.get(c.name) ?? (targets.length === 1 ? targets[0] : undefined);
    if (!t) return [];
    const failed = c.outcome === 'failed' || c.outcome === 'error';
    return [
      {
        targetId: t.id,
        name: c.name,
        suitePath: t.path,
        outcome: failed ? 'failed' : c.outcome === 'skipped' ? 'skipped' : 'passed',
        ...(failed ? { failureKind: 'assertion' as const } : {}),
        ...(c.timeSeconds !== undefined ? { durationMs: Math.round(c.timeSeconds * 1000) } : {}),
        ...(c.message ? { messageExcerpt: c.message.slice(0, 2000) } : {}),
        rawStatus: c.outcome,
      },
    ];
  });
}
