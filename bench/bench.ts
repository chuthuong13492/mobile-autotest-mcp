/**
 * OPS-005 benchmarks against NFR-003: P0 inspection tools answer in ≤ 5 s at p95 on a 10k-file repository, and
 * `run_tests` returns in ≤ 2 s at p95. The repository is synthetic and Flutter-shaped (10,000 files, 2,000 of them
 * tests); calls go through the full server composition (middleware, audit, storage) in process, with the fake
 * runner. Writes `bench/RESULTS.md` and exits 1 when a target is missed.
 *
 * Usage: `pnpm bench` (Node 24+). Optional: BENCH_ITERATIONS (default 20).
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { performance } from 'node:perf_hooks';
import { composeRuns, runnablePlan, sc, setupRunData, waitTerminal } from '../apps/mcp-server/test/runSetup.ts';

const N = Number(process.env['BENCH_ITERATIONS'] ?? 20);
const TARGETS = { inspect_project: 5000, inspect_test_inventory: 5000, run_tests: 2000 } as const;

function p95(xs: number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.ceil(0.95 * s.length) - 1)]!;
}

/** 10,000 files: 2,000 tests, 6,000 lib files, 2,000 assets and other files. */
function bigRepo(ws: string) {
  const write = (rel: string, text: string) => {
    fs.mkdirSync(path.dirname(path.join(ws, rel)), { recursive: true });
    fs.writeFileSync(path.join(ws, rel), text);
  };
  for (let i = 0; i < 2000; i++) write(`test/feature_${i % 50}/case_${i}_test.dart`, '// fake: pass\nvoid main() {}\n');
  for (let i = 0; i < 6000; i++) write(`lib/feature_${i % 50}/file_${i}.dart`, `int f${i}() => ${i};\n`);
  for (let i = 0; i < 2000; i++) write(`assets/a_${i % 20}/img_${i}.txt`, 'x');
}

const f = setupRunData({ 'test/smoke_test.dart': 'pass' });
bigRepo(f.ws);
const c = await composeRuns(f.data);
const time = async (fn: () => Promise<unknown>) => {
  const t = performance.now();
  await fn();
  return performance.now() - t;
};

const samples: Record<keyof typeof TARGETS, number[]> = {
  inspect_project: [],
  inspect_test_inventory: [],
  run_tests: [],
};
let profile = '';
for (let i = 0; i < N; i++) {
  samples.inspect_project.push(
    await time(async () => {
      profile = sc<{ projectProfileId: string }>(
        await c.call('inspect_project', { workspace: 'ws_app', probeToolchains: false }),
      ).projectProfileId;
    }),
  );
  samples.inspect_test_inventory.push(
    await time(() => c.call('inspect_test_inventory', { projectProfileId: profile, limit: 200 })),
  );
}
const plan = await runnablePlan(c, ['test/smoke_test.dart']);
for (let i = 0; i < N; i++) {
  let runId = '';
  samples.run_tests.push(
    await time(async () => {
      runId = sc<{ runId: string }>(await c.call('run_tests', { planId: plan.planId, planHash: plan.planHash })).runId;
    }),
  );
  await waitTerminal(c, runId, 60_000);
}
await c.close();

const rows = (Object.keys(TARGETS) as (keyof typeof TARGETS)[]).map((k) => {
  const v = p95(samples[k]);
  return {
    k,
    p95: Math.round(v),
    median: Math.round(samples[k].sort((a, b) => a - b)[samples[k].length >> 1]!),
    target: TARGETS[k],
    ok: v <= TARGETS[k],
  };
});
const host = `${os.type()} ${os.release()} ${os.arch()}, ${os.cpus()[0]?.model ?? 'cpu'} ×${os.cpus().length}, Node ${process.versions.node}`;
const md = `# Benchmark results (OPS-005, NFR-003)

Generated by \`pnpm bench\` on ${new Date().toISOString().slice(0, 10)}: ${host}. ${N} iterations per tool on a synthetic
Flutter-shaped repository of 10,000 files (2,000 tests), through the full server composition with the fake runner.
\`run_tests\` is measured until it returns (the run itself is asynchronous).

| Tool | Median (ms) | p95 (ms) | Target p95 (ms) | Result |
|---|---|---|---|---|
${rows.map((r) => `| \`${r.k}\` | ${r.median} | ${r.p95} | ${r.target} | ${r.ok ? 'PASS' : 'FAIL'} |`).join('\n')}
`;
fs.writeFileSync(path.join(import.meta.dirname, 'RESULTS.md'), md);
console.log(md);
fs.rmSync(f.base, { recursive: true, force: true });
process.exit(rows.every((r) => r.ok) ? 0 : 1);
